CALLING_CODES: Final[tuple[Country, ...]] = tuple(
    Country(code, name, int(dial))
    for code, dial, name in (line.split(" ", 2) for line in _TABLE.splitlines() if line.strip())
)

_BY_CODE: Final[dict[str, Country]] = {entry.code: entry for entry in CALLING_CODES}

# Centurion Systems is a South African company; most accounts live on that datacentre.
HOME_COUNTRY: Final = "ZA"

# Numbers from these two countries are served by the Australian datacentre.
# The South African datacentre serves every other number, exactly as the app does.
_AU_DATACENTRE: Final = frozenset({"AU", "NZ"})


def country(code: str | None) -> Country | None:
    """The picker entry for an alpha-2 code, or None."""
    return _BY_CODE.get((code or "").strip().upper())


def datacentre_for_country(code: str | None) -> str:
    """The datacentre key (``za`` or ``au``) for an account registered in ``code``."""
    return "au" if (code or "").strip().upper() in _AU_DATACENTRE else "za"
