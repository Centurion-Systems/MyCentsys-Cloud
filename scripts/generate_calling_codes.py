"""Regenerate ``custom_components/mycentsys_cloud/calling_codes.py``.

The country list of the setup form is derived from public reference data, not
typed by hand:

* ISO 3166-1 alpha-2 codes and names from ``pycountry`` (the ISO data set),
  using the common name where ISO defines one ("Bolivia", not the long form);
* E.164 country calling codes from ``phonenumbers`` (Google's libphonenumber
  metadata, which follows the ITU-T E.164 assignments).

Regions that have a calling code but no ISO entry (Kosovo, Ascension Island)
are named here. Run with both packages installed::

    python scripts/generate_calling_codes.py > custom_components/mycentsys_cloud/calling_codes.py
"""

from __future__ import annotations

import sys
import unicodedata

import phonenumbers
import pycountry

# Calling-code regions ISO 3166-1 does not list (user-assigned or exceptionally reserved codes).
EXTRA_NAMES = {
    "XK": "Kosovo",
    "AC": "Ascension Island",
    "TA": "Tristan da Cunha",
}

# ISO names that read oddly in a picker, overridden with the usual short form.
SHORT_NAMES = {
    "BN": "Brunei",
    "CD": "Congo (Kinshasa)",
    "CG": "Congo (Brazzaville)",
    "FM": "Micronesia",
    "IR": "Iran",
    "KP": "North Korea",
    "KR": "South Korea",
    "LA": "Laos",
    "MD": "Moldova",
    "PS": "Palestine",
    "RU": "Russia",
    "SH": "Saint Helena",
    "SY": "Syria",
    "TW": "Taiwan",
    "TZ": "Tanzania",
    "VA": "Vatican City",
    "VE": "Venezuela",
    "VG": "British Virgin Islands",
    "VI": "U.S. Virgin Islands",
    "VN": "Vietnam",
}


def _display_name(code: str) -> str | None:
    if code in EXTRA_NAMES:
        return EXTRA_NAMES[code]
    if code in SHORT_NAMES:
        return SHORT_NAMES[code]
    country = pycountry.countries.get(alpha_2=code)
    if country is None:
        return None
    return getattr(country, "common_name", None) or country.name


def _sort_key(name: str) -> str:
    """Alphabetical by the unaccented name, so Åland sorts with the A's."""
    return unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode().lower()


def main() -> int:
    rows: list[tuple[str, str, int]] = []
    for code in phonenumbers.SUPPORTED_REGIONS:
        dial = phonenumbers.country_code_for_region(code)
        name = _display_name(code)
        if dial <= 0 or not name:
            continue
        rows.append((code, name, dial))
    rows.sort(key=lambda row: _sort_key(row[1]))

    out = sys.stdout
    out.reconfigure(encoding="utf-8")
    out.write('"""Country calling codes for the setup form.\n\n')
    out.write("Generated by ``scripts/generate_calling_codes.py`` from ISO 3166-1 (names and\n")
    out.write("alpha-2 codes) and the E.164 country calling codes; do not edit by hand.\n")
    out.write('Each line of the table is ``<alpha-2> <calling code> <display name>``.\n"""\n\n')
    out.write("from __future__ import annotations\n\n")
    out.write("from typing import Final, NamedTuple\n\n")
    out.write('__all__ = ["Country", "CALLING_CODES", "HOME_COUNTRY", "country", "datacentre_for_country"]\n\n\n')
    out.write("class Country(NamedTuple):\n")
    out.write('    """One entry of the picker: ISO alpha-2 code, display name, E.164 calling code."""\n\n')
    out.write("    code: str\n    name: str\n    dial: int\n\n\n")
    out.write('_TABLE: Final = """\\\n')
    for code, name, dial in rows:
        out.write(f"{code} {dial} {name}\n")
    out.write('"""\n\n')
    out.write("CALLING_CODES: Final[tuple[Country, ...]] = tuple(\n")
    out.write("    Country(code, name, int(dial))\n")
    out.write('    for code, dial, name in (line.split(" ", 2) for line in _TABLE.splitlines() if line.strip())\n')
    out.write(")\n\n")
    out.write("_BY_CODE: Final[dict[str, Country]] = {entry.code: entry for entry in CALLING_CODES}\n\n")
    out.write('# Centurion Systems is a South African company; most accounts live on that datacentre.\n')
    out.write('HOME_COUNTRY: Final = "ZA"\n\n')
    out.write("# Numbers from these two countries are served by the Australian datacentre.\n")
    out.write("# The South African datacentre serves every other number, exactly as the app does.\n")
    out.write('_AU_DATACENTRE: Final = frozenset({"AU", "NZ"})\n\n\n')
    out.write("def country(code: str | None) -> Country | None:\n")
    out.write('    """The picker entry for an alpha-2 code, or None."""\n')
    out.write('    return _BY_CODE.get((code or "").strip().upper())\n\n\n')
    out.write("def datacentre_for_country(code: str | None) -> str:\n")
    out.write('    """The datacentre key (``za`` or ``au``) for an account registered in ``code``."""\n')
    out.write('    return "au" if (code or "").strip().upper() in _AU_DATACENTRE else "za"\n')
    return 0


if __name__ == "__main__":
    sys.exit(main())
